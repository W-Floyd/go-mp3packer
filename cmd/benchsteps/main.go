// Command benchsteps measures the performance history of this repository and
// writes the result into the README.
//
// The numbers in the README's step tables used to be transcribed by hand, one
// row per sitting, which made them awkward in three ways: a row could only be
// compared with its immediate neighbour, re-measuring one row meant editing
// prose, and a step invisible on the benchmark a table used could be recorded as
// nothing when it was really only unmeasured. This runs every step from a
// checkout of its own commit and regenerates the tables from the result.
//
//	benchsteps run     # top up bench/results.json until the medians settle
//	benchsteps inject  # rewrite the README's tables from that file
//
// Each step is built from a detached worktree of its own commit with one extra
// file added — the harness below — so that every commit is measured by the same
// benchmark over the same input, whatever benchmarks and test data it happened
// to ship with. Nothing else in the worktree is touched, so each commit's own
// code is what runs.
//
// # Caching
//
// A full sweep of the history costs minutes and mostly re-derives numbers that
// have already settled, so runs accumulate in bench/results.json rather than
// replacing it. Each pass measures only the cells that are still moving and
// stops when every one of them has settled, which makes a re-run after adding
// one commit cost about as much as that one commit.
//
// What makes a cached run reusable is a fingerprint: the machine, its OS and CPU,
// the Go toolchain, this tool's own source, and each input's contents together
// with the worker count and benchtime it is measured at. Any of those changing
// invalidates what it affects — the whole file for a machine or toolchain
// change, one input's cells for a change to that input — because a median mixed
// across two machines is not a measurement of either. Nothing here can tell that
// the machine got busy, so a suspicious cell is best deleted by hand or with
// -force.
//
// Runs are interleaved in a rotating order: a fixed order gives whichever
// binary always goes last a systematic penalty on a machine that is warming up,
// which is enough to turn a level result into a 1% regression.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"math"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"slices"
	"strconv"
	"strings"
	"syscall"
)

// measurementVersion is bumped by hand when a change here alters what a run
// measures — the flags passed to the test binary, the environment it sees, how
// its output is read. Together with a digest of the harness it forms the tool's
// half of the fingerprint.
//
// Hashing this whole file would be the automatic way to do that, and it was the
// first attempt, but it is the wrong knife: editing a comment or the caching
// logic would discard hours of measurement that remains perfectly valid, and the
// temptation to then reach for -force defeats the point of having a fingerprint
// at all. This is narrower and needs the discipline of remembering to bump it.
const measurementVersion = 1

// harness is written into each worktree before it is built. It deliberately
// does not use the commit's own benchmarks or test data: those changed over the
// history being measured, and a step table is only meaningful if every row was
// produced by the same measurement. Options has been source-compatible since
// the first commit, which is what makes this possible at all.
const harness = `package mp3packer

// Code generated by cmd/benchsteps. DO NOT EDIT.

import (
	"os"
	"strconv"
	"testing"
)

func BenchmarkBenchStep(b *testing.B) {
	data, err := os.ReadFile(os.Getenv("BENCHSTEP_FILE"))
	if err != nil {
		b.Fatal(err)
	}
	workers, err := strconv.Atoi(os.Getenv("BENCHSTEP_WORKERS"))
	if err != nil {
		b.Fatal(err)
	}
	b.SetBytes(int64(len(data)))
	for b.Loop() {
		if _, _, err := Process(data, Options{Recompress: true, Workers: workers}); err != nil {
			b.Fatal(err)
		}
	}
}
`

type config struct {
	Inputs []input `json:"inputs"`
	Tables []table `json:"tables"`
	Steps  []step  `json:"steps"`
}

type input struct {
	ID        string `json:"id"`
	Path      string `json:"path"`
	Workers   int    `json:"workers"`
	Benchtime string `json:"benchtime"`

	// Tolerance overrides -tolerance for this input, zero meaning use the flag.
	// An all-cores figure is inherently noisier than a single-worker one —
	// sixteen workers contending, and the collector running against them — and
	// sits around 1.5% however many runs it is given. Holding it to the same
	// target as a quiet one buys nothing and costs every run up to the cap.
	Tolerance float64 `json:"tolerance,omitempty"`
}

type table struct {
	ID string `json:"id"`

	// SigFigs is how many significant figures to quote, three by default.
	// Fixed decimals are wrong here because one table spans 2000 ms to 18: at
	// two decimals the first row reads 2122.57, which claims a precision the
	// half-percent settling target does not support.
	SigFigs int      `json:"sigFigs,omitempty"`
	Columns []column `json:"columns"`
}

type column struct {
	Input  string `json:"input"`
	Header string `json:"header"`

	// Delta adds a column beside this one giving the change from the row above.
	//
	// It is the figure to quote and the figure to compare against another
	// sitting. An absolute millisecond count is only meaningful next to the other
	// absolutes taken with it — this machine drifts about 7% between sittings, so
	// a row measured today and a row measured last week say more about the
	// weather than about the code. A ratio between two rows of the same session
	// divides that out, which is why the steps quoted in the prose are
	// percentages and not times.
	Delta bool `json:"delta,omitempty"`
}

type step struct {
	Commit string   `json:"commit"`
	Label  string   `json:"label"`
	Tables []string `json:"tables"`
}

// fingerprint is everything that would make two runs incomparable. It is stored
// beside the measurements and checked before any of them is reused.
type fingerprint struct {
	GOOS      string `json:"goos"`
	GOARCH    string `json:"goarch"`
	NumCPU    int    `json:"numCPU"`
	CPU       string `json:"cpu"`
	OSVersion string `json:"osVersion"`
	GoVersion string `json:"goVersion"`
	Tool      string `json:"tool"` // digest of this command's source
}

// results is what run writes and inject reads. Every individual run is kept
// rather than only the median: the spread is the only way to tell a real step
// from a restless machine, a reader who wants a different summary should not
// have to re-measure to get one, and topping up needs the runs it is adding to.
type results struct {
	Fingerprint fingerprint       `json:"fingerprint"`
	InputPrints map[string]string `json:"inputFingerprints"`
	Tolerance   float64           `json:"tolerance"`
	MinRounds   int               `json:"minRounds"`

	// Session numbers every invocation, because the machine is not the same from
	// one to the next. Between two sittings the whole history moved 7% on this
	// one, which is larger than most of the steps in the tables, so a median
	// mixed across sittings compares a change against the weather. Topping up a
	// cell cheaply is still worth having while iterating; what it cannot do is
	// produce a publishable table, and inject enforces that rather than trusting
	// whoever runs it to remember.
	Session int          `json:"session"`
	Inputs  []input      `json:"inputs"`
	Tables  []table      `json:"tables"`
	Steps   []stepResult `json:"steps"`
}

type stepResult struct {
	Commit string               `json:"commit"`
	Label  string               `json:"label"`
	Tables []string             `json:"tables"`
	Skip   string               `json:"skip,omitempty"` // why this step has no numbers
	Cells  map[string]*cellRuns `json:"cells,omitempty"`

	// Legacy is what this file used to hold: runs with no record of when they
	// were taken. Read once, to migrate, and never written.
	Legacy map[string][]float64 `json:"nsPerOp,omitempty"`
}

// cellRuns is one step measured on one input. The two slices run in step: Ns[i]
// was taken in session Session[i].
type cellRuns struct {
	Ns      []float64 `json:"ns"`
	Session []int     `json:"session"`
}

func (c *cellRuns) add(ns float64, session int) {
	c.Ns = append(c.Ns, ns)
	c.Session = append(c.Session, session)
}

// inSession returns the runs taken in one session, or all of them for session 0.
func (c *cellRuns) inSession(session int) []float64 {
	if c == nil {
		return nil
	}
	if session == 0 {
		return c.Ns
	}
	var out []float64
	for i, v := range c.Ns {
		if i < len(c.Session) && c.Session[i] == session {
			out = append(out, v)
		}
	}
	return out
}

// sessions lists every session this cell holds runs from.
func (c *cellRuns) sessions() map[int]int {
	n := map[int]int{}
	if c == nil {
		return n
	}
	for _, s := range c.Session {
		n[s]++
	}
	return n
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: benchsteps run|inject [flags]")
		os.Exit(2)
	}
	var err error
	switch os.Args[1] {
	case "run":
		err = runCmd(os.Args[2:])
	case "inject":
		err = injectCmd(os.Args[2:])
	default:
		fmt.Fprintf(os.Stderr, "unknown subcommand %q\n", os.Args[1])
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "benchsteps: %v\n", err)
		os.Exit(1)
	}
}

func runCmd(args []string) error {
	fs := flag.NewFlagSet("run", flag.ExitOnError)
	cfgPath := fs.String("config", "bench/steps.json", "step list")
	outPath := fs.String("out", "bench/results.json", "measurements, read as a cache and written back")
	minRounds := fs.Int("min-rounds", 5, "runs to take before judging a cell settled")
	maxRounds := fs.Int("max-rounds", 250, "runs after which a cell is left unsettled; 0 for no limit")
	tol := fs.Float64("tolerance", 0.0075, "settled when the median's standard error is under this fraction of it")
	force := fs.Bool("force", false, "discard cached runs and measure from scratch")
	sweep := fs.Bool("sweep", false, "measure every cell in this session, which is what inject requires")
	adopt := fs.Bool("adopt", false, "accept a cache that carries no fingerprint as this machine's")
	cacheDir := fs.String("build-cache", "bench/.build", "where built test binaries are kept between runs")
	if err := fs.Parse(args); err != nil {
		return err
	}

	var cfg config
	if err := readJSON(*cfgPath, &cfg); err != nil {
		return err
	}

	// Resolve inputs up front so that a missing file is reported once, before
	// anything is built, rather than as a wall of failed runs.
	paths, prints := map[string]string{}, map[string]string{}
	for _, in := range cfg.Inputs {
		p := os.ExpandEnv(in.Path)
		if p == "" {
			fmt.Fprintf(os.Stderr, "input %q: unset, skipping\n", in.ID)
			continue
		}
		abs, err := filepath.Abs(p)
		if err != nil {
			return err
		}
		digest, err := fileDigest(abs)
		if err != nil {
			fmt.Fprintf(os.Stderr, "input %q: %v, skipping\n", in.ID, err)
			continue
		}
		paths[in.ID] = abs
		prints[in.ID] = digestOf(digest, strconv.Itoa(in.Workers), in.Benchtime)
	}

	fp := takeFingerprint()
	out := loadCache(*outPath, fp, prints, *force, *adopt)
	out.Fingerprint, out.InputPrints, out.Tolerance = fp, prints, *tol
	out.MinRounds = *minRounds
	out.Session++
	session := out.Session
	if *sweep {
		fmt.Fprintf(os.Stderr, "session %d, sweeping every cell\n", session)
	} else {
		fmt.Fprintf(os.Stderr, "session %d, topping up unsettled cells only "+
			"(inject needs -sweep)\n", session)
	}
	out.Inputs, out.Tables = cfg.Inputs, cfg.Tables

	// Carry forward whatever the cache already holds for each configured step,
	// matched on commit: a label is prose and re-measuring for one would be
	// absurd.
	steps := make([]stepResult, 0, len(cfg.Steps))
	for _, s := range cfg.Steps {
		res := stepResult{Commit: s.Commit, Label: s.Label, Tables: s.Tables}
		if i := slices.IndexFunc(out.Steps, func(o stepResult) bool { return o.Commit == s.Commit }); i >= 0 {
			res.Cells = out.Steps[i].Cells
		}
		if res.Cells == nil {
			res.Cells = map[string]*cellRuns{}
		}
		steps = append(steps, res)
	}
	out.Steps = steps

	// Which cells still need runs. Doing this before building means a sweep that
	// is entirely cached costs nothing at all, which is the point.
	type cell struct {
		step  int
		input input
	}
	pending := func() []cell {
		var c []cell
		for i := range out.Steps {
			if out.Steps[i].Skip != "" {
				continue
			}
			for _, in := range cfg.Inputs {
				if _, ok := paths[in.ID]; !ok {
					continue
				}
				if !slices.Contains(out.Steps[i].Tables, tableOf(cfg, in.ID)) {
					continue
				}
				// Topping up judges a cell by every run it has, which is what
				// makes it cheap. A sweep judges it by this session's runs
				// alone, so every cell is measured again and the table it
				// produces is internally comparable.
				have := out.Steps[i].Cells[in.ID]
				judge := have.inSession(0) // every run it has
				if *sweep {
					judge = have.inSession(session)
				}
				if *maxRounds > 0 && len(judge) >= *maxRounds {
					continue // given up on; see the run limit in provenance
				}
				if settled(judge, tolFor(in, *tol), *minRounds) {
					continue
				}
				c = append(c, cell{i, in})
			}
		}
		return c
	}

	todo := pending()
	if len(todo) == 0 {
		fmt.Fprintln(os.Stderr, "every cell already settled; nothing to measure")
		return writeJSON(*outPath, out)
	}

	// Two of these running at once would interleave writes to the cache and,
	// worse, contend for the machine — which does not fail, it just produces
	// numbers that are quietly wrong.
	unlock, err := lock(*outPath + ".lock")
	if err != nil {
		return err
	}
	defer unlock()

	// Test binaries are kept between runs. A commit's code cannot change, so the
	// only things that make a binary stale are the harness and the toolchain, and
	// both are in the name — a stale one is never picked up, it is simply never
	// asked for again. Without this every invocation paid twenty worktrees and
	// twenty builds, about a minute, before measuring anything.
	buildKey := digestOf(harness, fp.GoVersion, fp.GOOS, fp.GOARCH)
	if err := os.MkdirAll(*cacheDir, 0o755); err != nil {
		return err
	}

	// Build only the commits with work outstanding.
	bins := map[string]string{}
	for _, c := range todo {
		commit := out.Steps[c.step].Commit
		if _, ok := bins[commit]; ok {
			continue
		}
		bin, err := build(*cacheDir, commit, buildKey)
		if err != nil {
			out.Steps[c.step].Skip = err.Error()
			fmt.Fprintf(os.Stderr, "%s: %v\n", commit, err)
			continue
		}
		bins[commit] = bin
	}

	for pass := 0; ; pass++ {
		todo = pending()
		todo = slices.DeleteFunc(todo, func(c cell) bool {
			_, ok := bins[out.Steps[c.step].Commit]
			return !ok
		})
		if len(todo) == 0 {
			break
		}
		// Rotate the starting point each pass. See the package comment.
		for k := range todo {
			c := todo[(k+pass)%len(todo)]
			s := &out.Steps[c.step]
			ns, err := measure(bins[s.Commit], c.input, paths[c.input.ID])
			if err != nil {
				fmt.Fprintf(os.Stderr, "%s/%s: %v\n", s.Commit, c.input.ID, err)
				s.Skip = err.Error()
				continue
			}
			if s.Cells[c.input.ID] == nil {
				s.Cells[c.input.ID] = &cellRuns{}
			}
			s.Cells[c.input.ID].add(ns, session)
			runs := s.Cells[c.input.ID].Ns
			if *sweep {
				runs = s.Cells[c.input.ID].inSession(session)
			}
			fmt.Fprintf(os.Stderr, "%-8s %-8s %8.2f ms  n=%-3d se=%.2f%% (target %.2f%%)\n",
				s.Commit, c.input.ID, ns/1e6, len(runs), 100*relSE(runs), 100*tolFor(c.input, *tol))
		}
		// Write as we go: a sweep of the whole history is long enough that
		// losing it to an interruption would be worse than the extra writes.
		if err := writeJSON(*outPath, out); err != nil {
			return err
		}
		progress(os.Stderr, out, cfg, session, *sweep, pass+1, *tol)
	}
	return writeJSON(*outPath, out)
}

// progress prints the medians so far after each pass. A sweep takes long enough
// that watching the individual runs go by says little — what is worth seeing is
// the shape of the table forming, and whether a row is settling or wandering.
// Cells still short of their target are marked, so it is clear which numbers are
// still moving and which are done.
func progress(w io.Writer, out results, cfg config, session int, sweep bool, pass int, tol float64) {
	fmt.Fprintf(w, "\n=== pass %d, session %d: medians so far, ms ===\n", pass, session)

	ids := make([]string, 0, len(cfg.Inputs))
	for _, in := range cfg.Inputs {
		ids = append(ids, in.ID)
	}
	label := 0
	for _, s := range out.Steps {
		label = max(label, len(s.Label))
	}
	fmt.Fprintf(w, "%-*s", label, "")
	for _, id := range ids {
		fmt.Fprintf(w, "  %14s", id)
	}
	fmt.Fprintln(w)

	for _, s := range out.Steps {
		fmt.Fprintf(w, "%-*s", label, s.Label)
		for _, id := range ids {
			runs := s.Cells[id].inSession(0)
			if sweep {
				runs = s.Cells[id].inSession(session)
			}
			if len(runs) == 0 {
				fmt.Fprintf(w, "  %14s", "—")
				continue
			}
			// A trailing ? is a cell whose median is still moving; a bare number
			// is one that has reached its target and will not be measured again.
			mark := " "
			var want float64 = tol
			if i := slices.IndexFunc(cfg.Inputs, func(x input) bool { return x.ID == id }); i >= 0 {
				want = tolFor(cfg.Inputs[i], tol)
			}
			if relSE(runs) > want {
				mark = "?"
			}
			fmt.Fprintf(w, "  %10s%s%-3s", sigFigs(median(runs)/1e6, 4), mark, fmt.Sprintf("%d", len(runs)))
		}
		fmt.Fprintln(w)
	}
	fmt.Fprintln(w)
}

// loadCache reads previous measurements, keeping only what is still comparable.
// A change to the machine, the toolchain or this tool drops everything; a change
// to one input drops that input's cells and leaves the rest.
func loadCache(path string, fp fingerprint, prints map[string]string, force, adopt bool) results {
	var old results
	if force {
		return results{}
	}
	if err := readJSON(path, &old); err != nil {
		return results{}
	}
	// A cache written before fingerprinting existed has nothing to compare, and
	// adopting it silently would defeat the whole mechanism — so it takes -adopt,
	// by which the caller asserts the runs came from this machine.
	if (old.Fingerprint == fingerprint{}) && len(old.Steps) > 0 {
		if !adopt {
			return results{}
		}
		fmt.Fprintln(os.Stderr, "adopting an unfingerprinted cache as this machine's")
		old.Fingerprint = fp
		for id := range prints {
			if old.InputPrints == nil {
				old.InputPrints = map[string]string{}
			}
			old.InputPrints[id] = prints[id]
		}
	}
	// Runs from before sessions were recorded become session 0, which inject
	// treats as "no session" and so will not publish. They are kept because they
	// are still worth topping up from, not because they can be trusted together.
	for i := range old.Steps {
		if len(old.Steps[i].Legacy) == 0 {
			continue
		}
		if old.Steps[i].Cells == nil {
			old.Steps[i].Cells = map[string]*cellRuns{}
		}
		for id, ns := range old.Steps[i].Legacy {
			c := &cellRuns{Ns: ns, Session: make([]int, len(ns))}
			old.Steps[i].Cells[id] = c
		}
		old.Steps[i].Legacy = nil
	}
	if diff := fingerprintDiff(old.Fingerprint, fp); diff != "" {
		fmt.Fprintf(os.Stderr, "discarding cached runs: %s\n", diff)
		return results{}
	}
	for id, want := range prints {
		if got, ok := old.InputPrints[id]; ok && got != want {
			fmt.Fprintf(os.Stderr, "discarding cached runs for input %q: it or its settings changed\n", id)
			for i := range old.Steps {
				delete(old.Steps[i].Cells, id)
			}
		}
	}
	return old
}

func fingerprintDiff(a, b fingerprint) string {
	var d []string
	add := func(name, x, y string) {
		if x != y {
			d = append(d, fmt.Sprintf("%s %q -> %q", name, x, y))
		}
	}
	add("goos", a.GOOS, b.GOOS)
	add("goarch", a.GOARCH, b.GOARCH)
	add("cpus", strconv.Itoa(a.NumCPU), strconv.Itoa(b.NumCPU))
	add("cpu", a.CPU, b.CPU)
	add("os version", a.OSVersion, b.OSVersion)
	add("go version", a.GoVersion, b.GoVersion)
	if a.Tool != b.Tool {
		d = append(d, "benchsteps itself changed")
	}
	return strings.Join(d, "; ")
}

func takeFingerprint() fingerprint {
	fp := fingerprint{
		GOOS:      runtime.GOOS,
		GOARCH:    runtime.GOARCH,
		NumCPU:    runtime.NumCPU(),
		GoVersion: strings.TrimSpace(capture("go", "env", "GOVERSION")),
		Tool:      digestOf(harness, strconv.Itoa(measurementVersion)),
	}
	switch runtime.GOOS {
	case "darwin":
		fp.CPU = strings.TrimSpace(capture("sysctl", "-n", "machdep.cpu.brand_string"))
		fp.OSVersion = strings.TrimSpace(capture("sw_vers", "-productVersion"))
	case "linux":
		if b, err := os.ReadFile("/proc/cpuinfo"); err == nil {
			for _, line := range strings.Split(string(b), "\n") {
				if name, v, ok := strings.Cut(line, ":"); ok && strings.TrimSpace(name) == "model name" {
					fp.CPU = strings.TrimSpace(v)
					break
				}
			}
		}
		fp.OSVersion = strings.TrimSpace(capture("uname", "-r"))
	default:
		fp.OSVersion = strings.TrimSpace(capture("uname", "-sr"))
	}
	// A probe that fails leaves its field empty, which still fingerprints
	// consistently on that machine; it just distinguishes less.
	if fp.GoVersion == "" {
		fp.GoVersion = runtime.Version()
	}
	return fp
}

func capture(name string, args ...string) string {
	out, err := exec.Command(name, args...).Output()
	if err != nil {
		return ""
	}
	return string(out)
}

// settled reports whether a cell has enough runs for its median to be worth
// quoting: the median's standard error, as a fraction of the median, under tol.
//
// The spread is estimated from the median absolute deviation rather than the
// standard deviation, because benchmark noise is one-sided — a run is delayed by
// other work on the machine, never hurried by it — and one such run would
// otherwise dominate. MAD can be zero with few samples and equal values, which
// would call a cell settled far too early, so a quarter of the range is used as
// a floor.
func settled(runs []float64, tol float64, min int) bool {
	if len(runs) < min {
		return false
	}
	return relSE(runs) <= tol
}

// tolFor is the settling target for an input: its own if it sets one, else the
// flag's.
func tolFor(in input, dflt float64) float64 {
	if in.Tolerance > 0 {
		return in.Tolerance
	}
	return dflt
}

func relSE(runs []float64) float64 {
	if len(runs) < 2 {
		return math.Inf(1)
	}
	med := median(runs)
	if med == 0 {
		return math.Inf(1)
	}
	dev := make([]float64, len(runs))
	for i, v := range runs {
		dev[i] = math.Abs(v - med)
	}
	sigma := 1.4826 * median(dev)
	lo, hi := slices.Min(runs), slices.Max(runs)
	if floor := (hi - lo) / 4; floor > sigma {
		sigma = floor
	}
	// 1.253 is the median's standard error relative to the mean's, for a normal
	// sample; the estimate is rough either way and only decides when to stop.
	return 1.253 * sigma / math.Sqrt(float64(len(runs))) / med
}

// tableOf reports which table an input feeds. An input belongs to exactly one
// table, which keeps the config from having to repeat the mapping twice.
func tableOf(cfg config, inputID string) string {
	for _, t := range cfg.Tables {
		for _, c := range t.Columns {
			if c.Input == inputID {
				return t.ID
			}
		}
	}
	return ""
}

// build returns a test binary for a commit, compiling it if the cache has none.
// The worktree exists only for the compile and is removed straight after: what
// is worth keeping is the binary, not the checkout.
func build(cacheDir, commit, key string) (string, error) {
	bin, err := filepath.Abs(filepath.Join(cacheDir, commit+"-"+key+".test"))
	if err != nil {
		return "", err
	}
	if _, err := os.Stat(bin); err == nil {
		return bin, nil
	}

	parent, err := os.MkdirTemp("", "benchsteps")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(parent)
	wt := filepath.Join(parent, commit)
	if out, err := exec.Command("git", "worktree", "add", "--detach", wt, commit).CombinedOutput(); err != nil {
		return "", fmt.Errorf("worktree: %v: %s", err, out)
	}
	defer exec.Command("git", "worktree", "remove", "--force", wt).Run()

	if err := os.WriteFile(filepath.Join(wt, "zz_benchstep_test.go"), []byte(harness), 0o644); err != nil {
		return "", err
	}
	fmt.Fprintf(os.Stderr, "building %s\n", commit)
	cmd := exec.Command("go", "test", "-c", "-o", bin, ".")
	cmd.Dir = wt
	if out, err := cmd.CombinedOutput(); err != nil {
		return "", fmt.Errorf("build: %v: %s", err, lastLines(string(out), 3))
	}
	return bin, nil
}

var nsPerOp = regexp.MustCompile(`\s(\d+(?:\.\d+)?)\s+ns/op`)

func measure(bin string, in input, path string) (float64, error) {
	cmd := exec.Command(bin, "-test.run", "^$", "-test.bench", "BenchmarkBenchStep",
		"-test.benchtime", in.Benchtime)
	cmd.Env = append(os.Environ(),
		"BENCHSTEP_FILE="+path,
		"BENCHSTEP_WORKERS="+strconv.Itoa(in.Workers))
	out, err := cmd.CombinedOutput()
	if err != nil {
		return 0, fmt.Errorf("%v: %s", err, lastLines(string(out), 3))
	}
	m := nsPerOp.FindStringSubmatch(string(out))
	if m == nil {
		return 0, fmt.Errorf("no ns/op in output: %s", lastLines(string(out), 3))
	}
	return strconv.ParseFloat(m[1], 64)
}

func injectCmd(args []string) error {
	fs := flag.NewFlagSet("inject", flag.ExitOnError)
	cfgPath := fs.String("config", "bench/steps.json", "step list, which decides what is shown and in what order")
	resPath := fs.String("results", "bench/results.json", "measurements")
	readme := fs.String("readme", "README.md", "file to rewrite")
	if err := fs.Parse(args); err != nil {
		return err
	}
	var res results
	if err := readJSON(*resPath, &res); err != nil {
		return err
	}
	// Presentation comes from the config and only the runs come from the cache,
	// so that renaming a column or reordering the steps does not need the history
	// re-measured. Runs are matched to steps by commit.
	var cfg config
	if err := readJSON(*cfgPath, &cfg); err != nil {
		return err
	}
	res.Inputs, res.Tables = cfg.Inputs, cfg.Tables
	steps := make([]stepResult, 0, len(cfg.Steps))
	for _, c := range cfg.Steps {
		sr := stepResult{Commit: c.Commit, Label: c.Label, Tables: c.Tables}
		if i := slices.IndexFunc(res.Steps, func(o stepResult) bool { return o.Commit == c.Commit }); i >= 0 {
			sr.Cells = res.Steps[i].Cells
		}
		steps = append(steps, sr)
	}
	res.Steps = steps

	body, err := os.ReadFile(*readme)
	if err != nil {
		return err
	}
	session, err := publishable(res)
	if err != nil {
		return err
	}
	res.Session = session

	text := string(body)
	for _, t := range res.Tables {
		rendered, err := render(res, t)
		if err != nil {
			return err
		}
		text, err = replaceBlock(text, t.ID, rendered)
		if err != nil {
			return err
		}
	}
	text, err = replaceBlock(text, "provenance", provenance(res))
	if err != nil {
		return err
	}
	return os.WriteFile(*readme, []byte(text), 0o644)
}

// provenance describes where the numbers came from, so that a reader comparing
// them against their own machine knows what they are comparing against. The run
// counts differ per cell, since each one is measured until it settles, so the
// range is reported rather than a single figure.
func provenance(res results) string {
	lo, hi, unsettled := math.MaxInt32, 0, 0
	tol := map[string]float64{}
	for _, in := range res.Inputs {
		tol[in.ID] = tolFor(in, res.Tolerance)
	}
	for _, s := range res.Steps {
		for id, cell := range s.Cells {
			runs := cell.inSession(res.Session)
			if len(runs) == 0 {
				continue
			}
			lo, hi = min(lo, len(runs)), max(hi, len(runs))
			if relSE(runs) > tol[id] {
				unsettled++
			}
		}
	}
	if hi == 0 {
		return "No measurements recorded.\n"
	}
	fp := res.Fingerprint
	machine := strings.TrimSpace(fp.CPU)
	if machine == "" {
		machine = fp.GOOS + "/" + fp.GOARCH
	}
	runs := fmt.Sprintf("%d", hi)
	if lo != hi {
		runs = fmt.Sprintf("%d to %d", lo, hi)
	}
	targets := []string{}
	for _, in := range res.Inputs {
		targets = append(targets, fmt.Sprintf("%.1f%% for %s", 100*tol[in.ID], in.ID))
	}
	s := fmt.Sprintf("Measured on %s, %d cpus, %s, %s. Each figure is the median of %s runs,\n"+
		"taken until the standard error of the median fell under its target (%s).\n",
		machine, fp.NumCPU, fp.OSVersion, fp.GoVersion, runs, strings.Join(targets, ", "))
	if unsettled > 0 {
		s += fmt.Sprintf("%d of them hit the run limit without settling, and are the ones to\n"+
			"distrust first.\n", unsettled)
	}
	return s
}

// publishable returns the newest session that measured every cell of every table
// enough times to be quoted, and refuses if there is none.
//
// This is the whole reason sessions are recorded. Topping up leaves a file whose
// cells were measured at different times, and the machine is not the same from
// one time to the next — enough to invent a 3% step or hide one. Rather than
// warn, which is easy to skip past, inject will not write a table it cannot draw
// from a single session.
func publishable(res results) (int, error) {
	type missing struct {
		commit, input string
		have          int
	}
	// A file written before sessions were recorded has neither, and nothing in it
	// can be published; say so plainly rather than through a count of zero.
	if res.Session < 1 {
		return 0, errors.New("this file predates session recording, so none of its runs can be " +
			"placed in time and no table from it would be internally comparable; run with -sweep")
	}
	if res.MinRounds < 1 {
		res.MinRounds = 5
	}
	best := -1
	var why []missing
	for session := res.Session; session >= 1; session-- {
		var gaps []missing
		for _, s := range res.Steps {
			for _, t := range res.Tables {
				if !slices.Contains(s.Tables, t.ID) {
					continue
				}
				for _, c := range t.Columns {
					if !slices.ContainsFunc(res.Inputs, func(in input) bool { return in.ID == c.Input }) {
						continue
					}
					n := len(s.Cells[c.Input].inSession(session))
					if n < res.MinRounds {
						gaps = append(gaps, missing{s.Commit, c.Input, n})
					}
				}
			}
		}
		if len(gaps) == 0 {
			best = session
			break
		}
		if why == nil {
			why = gaps
		}
	}
	if best < 0 {
		msg := fmt.Sprintf("no session has measured every cell at least %d times, so no table here "+
			"would be internally comparable; run with -sweep", res.MinRounds)
		for i, m := range why {
			if i == 3 {
				msg += fmt.Sprintf("\n  ... and %d more", len(why)-3)
				break
			}
			msg += fmt.Sprintf("\n  %s/%s has %d in the newest session", m.commit, m.input, m.have)
		}
		return 0, errors.New(msg)
	}
	return best, nil
}

func render(res results, t table) (string, error) {
	tol := map[string]float64{}
	for _, in := range res.Inputs {
		tol[in.ID] = tolFor(in, res.Tolerance)
	}

	var b strings.Builder
	b.WriteString("|")
	for _, c := range t.Columns {
		b.WriteString(" | " + c.Header)
		if c.Delta {
			b.WriteString(" | Δ")
		}
	}
	b.WriteString(" |\n| ---")
	for _, c := range t.Columns {
		b.WriteString(" | ---")
		if c.Delta {
			b.WriteString(" | ---")
		}
	}
	b.WriteString(" |\n")

	prev := map[string]float64{}
	for _, s := range res.Steps {
		if !slices.Contains(s.Tables, t.ID) {
			continue
		}
		var cells []string
		any := false
		for _, c := range t.Columns {
			runs := s.Cells[c.Input].inSession(res.Session)
			if len(runs) == 0 {
				cells = append(cells, "—")
				if c.Delta {
					cells = append(cells, "—")
				}
				continue
			}
			any = true
			v := median(runs) / 1e6
			cells = append(cells, sigFigs(v, t.SigFigs))
			if c.Delta {
				cells = append(cells, deltaCell(prev[c.Input], v, tol[c.Input]))
			}
			prev[c.Input] = v
		}
		if !any {
			continue // nothing measured for this row; leave it out rather than imply a gap
		}
		b.WriteString("| " + s.Label + " | " + strings.Join(cells, " | ") + " |\n")
	}
	return b.String(), nil
}

// worseFactor is how much more evidence an increase needs than a decrease before
// it is shown as a result.
//
// Benchmark noise is one-sided: a run can be delayed by other work on the
// machine and never hurried by it, so what noise there is pushes a median up.
// An apparent increase is therefore the direction noise already favours, and
// wants holding to a higher standard than an apparent decrease of the same size.
//
// The asymmetry of the consequences points the same way. Missing a real
// improvement costs a row that reads flat, and the improvement can be
// demonstrated elsewhere; publishing a regression that is not there sends the
// next person hunting something that does not exist, in a commit that is
// probably fine.
const worseFactor = 2

// deltaCell is the change from the previous row in per cent, or "≈" when the
// measurement cannot support a direction.
//
// Two medians each good to t differ by chance with a standard error near t root
// two, so a decrease has to reach about three t — a little over two sigma —
// before it means anything, and an increase worseFactor times that, a little
// over four.
//
// Anything short of that prints as "≈" rather than as a signed number in
// brackets, which is what it used to do. A bracket is not enough: "(+1.1%)" is
// read as a slight worsening by anyone skimming, and there is no evidence for a
// worsening at all. The honest content of such a cell is that nothing was
// measured, and several of these rows are steps that are real and demonstrated
// by other means, which the prose says.
func deltaCell(prev, v, tol float64) string {
	if prev == 0 {
		return "—"
	}
	d := 100 * (v - prev) / prev
	bar := 300 * tol
	if d > 0 {
		bar *= worseFactor
	}
	if math.Abs(d) < bar {
		return "≈"
	}
	// U+2212, to match the rest of the document rather than a hyphen.
	txt := strings.Replace(strconv.FormatFloat(d, 'f', 1, 64), "-", "\u2212", 1) + "%"
	if d > 0 {
		txt = "+" + txt
	}
	return txt
}

// sigFigs formats v to n significant figures, without exponent notation.
func sigFigs(v float64, n int) string {
	if n <= 0 {
		n = 3
	}
	d := n - 1
	if v > 0 {
		d = n - 1 - int(math.Floor(math.Log10(v)))
	}
	return strconv.FormatFloat(v, 'f', max(d, 0), 64)
}

func median(v []float64) float64 {
	s := slices.Clone(v)
	slices.Sort(s)
	n := len(s)
	if n%2 == 1 {
		return s[n/2]
	}
	return (s[n/2-1] + s[n/2]) / 2
}

// replaceBlock swaps the text between the markers for id. The markers are HTML
// comments, so they do not render, and their presence is required rather than
// created: silently appending a table to the end of a document is never what
// was wanted.
func replaceBlock(text, id, body string) (string, error) {
	open := "<!-- benchsteps:" + id + " -->"
	shut := "<!-- /benchsteps:" + id + " -->"
	i := strings.Index(text, open)
	j := strings.Index(text, shut)
	if i < 0 || j < 0 || j < i {
		return "", fmt.Errorf("markers for %q not found in the document", id)
	}
	return text[:i+len(open)] + "\n" + body + text[j:], nil
}

// lock takes an exclusive lock by creating a file holding the owner's pid.
//
// A run being killed part way through is entirely normal here — a sweep is long,
// and the results so far are written after every pass and remain valid — so a
// lock left behind by a process that no longer exists is taken over rather than
// treated as an error. Only a live holder blocks, which is the case that matters:
// two of these measuring at once would contend for the machine and produce
// numbers that are wrong without looking wrong.
func lock(path string) (func(), error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o644)
	if err != nil {
		held, rerr := os.ReadFile(path)
		if rerr != nil {
			return nil, err
		}
		pid, _ := strconv.Atoi(strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(string(held)), "pid")))
		if pid > 0 && alive(pid) {
			return nil, fmt.Errorf("another run holds %s (pid %d)", path, pid)
		}
		fmt.Fprintf(os.Stderr, "taking over a lock left by pid %d, which is gone\n", pid)
		if err := os.Remove(path); err != nil {
			return nil, err
		}
		return lock(path)
	}
	fmt.Fprintf(f, "pid %d\n", os.Getpid())
	f.Close()
	return func() { os.Remove(path) }, nil
}

func alive(pid int) bool {
	p, err := os.FindProcess(pid)
	if err != nil {
		return false
	}
	// Signal 0 checks for existence without delivering anything.
	return p.Signal(syscall.Signal(0)) == nil
}

func fileDigest(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	return digestOf(string(b)), nil
}

func digestOf(parts ...string) string {
	h := sha256.New()
	for _, p := range parts {
		h.Write([]byte(p))
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))[:16]
}

func readJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}

func writeJSON(path string, v any) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}

func lastLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, " / ")
}

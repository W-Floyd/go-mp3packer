package huffman

// The MPEG layer III Huffman code tables, as ISO/IEC 11172-3 and 13818-3 print
// them: a dense xlen-by-ylen grid of codewords indexed x-major, one row of the
// standard's table per line here. Each entry packs the codeword length above the
// codeword itself, which is everything the standard specifies about a table and
// all that is needed to derive the rest.
//
// Nothing about how a codeword is found lives in this file. The encode map, the
// ten-bit probe and the tree the probe falls back to are all derived from these
// grids, so the search strategy can change without touching the constants, and a
// constant can be checked against the standard's printed table without reading
// any of the search.
//
// This file is not generated and cannot usefully be: it is where the standard
// enters the program, and anything upstream of it would be some other project's
// transcription rather than the standard itself. Three things hold it in place
// instead of a generator:
//
//   - TestGridsAreValidCodeTables checks what the standard guarantees — every
//     code fits its length, no code prefixes another, and the Kraft sum of each
//     table is exactly 1. Nearly any mistyped digit breaks one of those.
//   - trees_gen.go is derived from these grids and committed, and
//     TestTreesGenerated fails when the two disagree. So an edit here that still
//     satisfies the invariants — two equal-length codewords swapped between
//     cells, say — cannot land quietly: it changes the generated trees, and the
//     change has to be deliberate.
//   - Those trees were checked once, slot for slot, against the tables of an
//     independent decoder, and matched exactly. They had to: a complete prefix
//     code over n codewords has 2n-1 nodes and one depth-first order, so the
//     flattening is forced. That is the external verification of the
//     transcription, and the generated file is what carries it forward.

// codeword is one grid cell: the code length in bits codeLenShift and above, the
// code itself below. The longest codeword the standard defines is 19 bits, so
// both halves fit a uint32 with room to spare.
type codeword uint32

const codeLenShift = 20

func (c codeword) length() int  { return int(c >> codeLenShift) }
func (c codeword) code() uint32 { return uint32(c) & (1<<codeLenShift - 1) }

// grid is one code table exactly as the standard tabulates it.
